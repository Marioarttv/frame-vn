import type { Project } from "./types";

/**
 * Imported media lives once in the local asset store and the project refers to it by content
 * hash. Portable files (JSON backups, HTML games) re-embed the bytes; nothing else changes.
 */
export const ASSET_REF_PATTERN = /^asset:([a-f0-9]{64})$/;

export function isAssetRef(value: unknown): value is string {
  return typeof value === "string" && ASSET_REF_PATTERN.test(value);
}

export function assetRef(hash: string): string {
  if (!/^[a-f0-9]{64}$/.test(hash)) throw new Error("Invalid asset hash.");
  return `asset:${hash}`;
}

export function assetHash(ref: string): string {
  const match = ASSET_REF_PATTERN.exec(ref);
  if (!match) throw new Error("Invalid asset reference.");
  return match[1];
}

export type MediaKind = "image" | "audio" | "video";

/**
 * Rewrites every media field a project can hold. Rig/cue JSON stays where it is: it is either
 * bundled by a local pack or generated by the voice service.
 */
export async function mapProjectMedia(
  project: Project,
  map: (src: string, kind: MediaKind) => string | Promise<string>,
): Promise<Project> {
  const media = async (src: string, kind: MediaKind) => map(src, kind);
  return {
    ...project,
    characters: await Promise.all(
      project.characters.map(async (character) => ({
        ...character,
        poses: await Promise.all(
          character.poses.map(async (pose) => ({
            ...pose,
            src: await media(pose.src, "image"),
          })),
        ),
        ...(character.voice
          ? {
              voice: {
                ...character.voice,
                src: await media(character.voice.src, "audio"),
              },
            }
          : {}),
      })),
    ),
    backgrounds: await Promise.all(
      project.backgrounds.map(async (background) => ({
        ...background,
        src: await media(
          background.src,
          background.kind === "video" ? "video" : "image",
        ),
      })),
    ),
    sounds: await Promise.all(
      project.sounds.map(async (sound) => ({
        ...sound,
        src: await media(sound.src, "audio"),
      })),
    ),
    nodes: await Promise.all(
      project.nodes.map(async (node) =>
        node.audioSrc
          ? { ...node, audioSrc: await media(node.audioSrc, "audio") }
          : node,
      ),
    ),
  };
}

/** Every media source in a project, synchronously. */
export function projectMediaSources(
  project: Project,
): { src: string; kind: MediaKind }[] {
  const sources: { src: string; kind: MediaKind }[] = [];
  const add = (src: string | undefined, kind: MediaKind) => {
    if (src) sources.push({ src, kind });
  };
  for (const character of project.characters) {
    character.poses.forEach((pose) => add(pose.src, "image"));
    add(character.voice?.src, "audio");
  }
  project.backgrounds.forEach((background) =>
    add(background.src, background.kind === "video" ? "video" : "image"),
  );
  project.sounds.forEach((sound) => add(sound.src, "audio"));
  project.nodes.forEach((node) => add(node.audioSrc, "audio"));
  return sources;
}

/** Every asset reference used by a project, for preloading and garbage collection. */
export function projectAssetRefs(project: Project): Set<string> {
  return new Set(
    projectMediaSources(project)
      .map(({ src }) => src)
      .filter(isAssetRef),
  );
}
