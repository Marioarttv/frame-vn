#!/usr/bin/env node
/** Deterministic inventory of the exact installed, locked dependency tree. */
import { readFile, readdir, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const lock = JSON.parse(await readFile(path.join(root, "package-lock.json"), "utf8"));
const inventory = [];
const texts = new Map();
for (const [relative, entry] of Object.entries(lock.packages).sort(([a], [b]) => a.localeCompare(b, "en"))) {
  if (!relative) continue;
  const name = entry.name || relative.split("node_modules/").at(-1);
  const directory = path.join(root, relative);
  let files;
  try {
    files = await readdir(directory);
  } catch (error) {
    if (error.code !== "ENOENT" || !entry.optional) throw error;
    continue; // Optional binaries for another operating system are not installed/distributed.
  }
  const licenses = files.filter((file) => /^(licen[cs]e|copying|notice)(\.|-|$)/i.test(file)).sort();
  const refs = [];
  for (const file of licenses) {
    const text = (await readFile(path.join(directory, file), "utf8")).replace(/\r\n/g, "\n").trim();
    const digest = createHash("sha256").update(text).digest("hex");
    const record = texts.get(digest) || { text, packages: [] };
    record.packages.push(`${name}@${entry.version} (${file})`);
    texts.set(digest, record);
    refs.push(digest);
  }
  inventory.push(`${name}@${entry.version} — ${entry.license || "UNDECLARED"}${entry.dev ? " [development]" : ""}\n  ${refs.length ? refs.map((hash) => `license SHA-256 ${hash}`).join("\n  ") : "No top-level license text found; see package metadata/upstream license."}`);
}
const sections = [...texts].map(([digest, record]) => `===== ${digest} =====\n${record.packages.join("\n")}\n\n${record.text}\n`);
const fonts = await Promise.all(["OFL-Cinzel.txt", "OFL-CormorantGaramond.txt"].map(async (file) =>
  `===== Bundled player font: ${file} =====\n${await readFile(path.join(root, "src/player/fonts", file), "utf8")}`,
));
await writeFile(path.join(root, "THIRD_PARTY_LICENSES.txt"),
  `Frame — installed third-party dependency notices\nGenerated by scripts/write-notices.mjs from package-lock.json and installed package license files.\n\n${inventory.join("\n\n")}\n\n${sections.join("\n")}\n${fonts.join("\n\n")}`,
);
console.log(`Recorded ${inventory.length} installed packages and ${texts.size} distinct license/notice texts.`);
