/** Rebuild only the original distributable examples; never reads private local packs. */
import path from "node:path";
import { mkdir, writeFile } from "node:fs/promises";
import { poseToRecipe } from "./character/workspace.mjs";
import { buildCharacterPack } from "./character/pack.mjs";
const cast = [];
for (const name of ["mira", "noah"]) {
  const { recipe, assetFiles } = await poseToRecipe(
    `art/characters/${name}/poses/neutral.json`,
    { store: false },
  );
  const outputDirectory = path.resolve(`public/assets/characters/${name}`);
  await mkdir(path.dirname(outputDirectory), { recursive: true });
  const result = await buildCharacterPack(recipe, {
    assetFiles,
    outputDirectory,
    urlRoot: `/assets/characters/${name}`,
  });
  cast.push(result.character);
  console.log(
    `${name}: ${result.validation.valid ? "valid" : "invalid"}; ${result.validation.warnings.join("; ")}`,
  );
}

await writeFile(
  "src/studio/example-cast.generated.ts",
  `// Generated by npm run examples:build.\nimport type { Character } from "../engine/types";\nexport const EXAMPLE_CAST: Character[] = ${JSON.stringify(cast, null, 2)};\n`,
);
